export function getTopicYieldsByExam(exam: ExamType): TopicYieldItem[] {
  return DOMAIN_TOPIC_WEIGHTAGES[exam] || DOMAIN_TOPIC_WEIGHTAGES.GATE;
}

export function getTopicYieldSummary(exam: ExamType) {
  const list = getTopicYieldsByExam(exam);
  const highYield = list.filter(t => t.yieldTier === 'high-yield');
  const mediumYield = list.filter(t => t.yieldTier === 'medium-yield');
  const lowYield = list.filter(t => t.yieldTier === 'low-yield');

  const highMarks = highYield.reduce((acc, t) => acc + t.marksContribution, 0);
  const medMarks = mediumYield.reduce((acc, t) => acc + t.marksContribution, 0);
  const lowMarks = lowYield.reduce((acc, t) => acc + t.marksContribution, 0);
  const totalTrackedMarks = highMarks + medMarks + lowMarks;

  const highHours = highYield.reduce((acc, t) => acc + t.avgStudyHours, 0);
  const totalHours = list.reduce((acc, t) => acc + t.avgStudyHours, 0);

  return {
    totalTopics: list.length,
    highYieldCount: highYield.length,
    mediumYieldCount: mediumYield.length,
    lowYieldCount: lowYield.length,
    highMarks,
    medMarks,
    lowMarks,
    totalTrackedMarks,
    highYieldMarksPercent: totalTrackedMarks > 0 ? Math.round((highMarks / totalTrackedMarks) * 100) : 0,
    highHours,
    totalHours,
    highYieldTimePercent: totalHours > 0 ? Math.round((highHours / totalHours) * 100) : 0
  };
}
